import { IsBoolean, IsOptional, IsString, IsUUID } from 'class-validator';

/*
Differences from the DB table structure:
- No id field, as it's auto-generated by the database.
- No createdAt & updatedAt fields, as they are not to be managed by the client.
*/
export class CreateNodeDto {
    @IsString()
    name!: string;

    @IsBoolean()
    isFolder!: boolean;

    @IsUUID()
    @IsOptional()
    parentId?: string;
};